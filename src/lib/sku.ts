// SKU хоосон орхигдсон үед ашиглана (Flutter форм болон Excel import
// скрипт хоёулаа ЭНЭ НЭГ функцийг ашигладаг тул хоёр газарт өөр өөр
// логик давхардахгүй).
//
// Формат: AUTO-XXXXXXXX (8 hex тэмдэгт, том үсгээр) — 4 тэрбум орчим
// боломжит хослол өгдөг тул давхцах магадлал бодит хэрэглээнд үл ойлгогдоно.
// ============================================================================

import crypto from "crypto";

export function generateSku(): string {
  const random = crypto.randomBytes(4).toString("hex").toUpperCase();
  return `AUTO-${random}`;
}
